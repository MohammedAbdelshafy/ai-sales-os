"""Output writers: next_actions.csv, exceptions.md, qualified.json, run_meta.json.

The first three are fully deterministic given identical inputs (no timestamps
embedded). run_meta.json holds run timestamp/ids/checksums and is allowed to
differ between runs.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime, timezone
from pathlib import Path


def write_next_actions(path: Path, records: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=["id", "action", "deadline", "reason"])
        writer.writeheader()
        for rec in records:
            writer.writerow(rec)


def write_exceptions(path: Path, evaluated: list[dict], cfg: dict) -> None:
    """Manager exception report. Deterministic: fixed section order, input row order."""
    missing, stale, out_of_band, suppressed = [], [], [], []

    for ev in evaluated:
        rid = (ev["row"].get("id") or "").strip() or f"row-{ev['row_number']}"
        co = (ev["row"].get("company") or "").strip()
        label = f"`{rid}` ({co})" if co else f"`{rid}`"
        row_ref = f"source row {ev['row_number']}"

        if ev["suppressed"]:
            suppressed.append(
                f"- {label}: {ev['suppression_evidence']} — {row_ref}")
            continue

        if not ev["rules"][0]["passed"]:
            missing.append(
                f"- {label}: {ev['rules'][0]['evidence']} — {row_ref}")

        days = ev["days_since_last_touch"]
        if days is not None and days > cfg["stale_after_days"]:
            stale.append(
                f"- {label}: last touch {days} days ago "
                f"(threshold {cfg['stale_after_days']}) — {row_ref}")
        elif days is None:
            stale.append(
                f"- {label}: {ev['rules'][4]['evidence']} — {row_ref}")

        val_rule = ev["rules"][1]
        if not val_rule["passed"] and ev["value_parsed"] is not None:
            out_of_band.append(
                f"- {label}: {val_rule['evidence']} — {row_ref}")
        elif not val_rule["passed"]:
            missing.append(
                f"- {label}: {val_rule['evidence']} — {row_ref}")

        dom_rule = ev["rules"][3]
        if not dom_rule["passed"]:
            suppressed.append(
                f"- {label}: {dom_rule['evidence']} — {row_ref}")

        stage_rule = ev["rules"][2]
        if not stage_rule["passed"]:
            suppressed.append(
                f"- {label}: {stage_rule['evidence']} — {row_ref}")

    lines = [
        "# Exceptions report",
        "",
        f"Generated by ai-sales-os for {len(evaluated)} opportunity records.",
        "",
        "## 1. Missing required data",
        "",
    ]
    lines += missing or ["_None._"]
    lines += ["", "## 2. Stale deals", ""]
    lines += stale or ["_None._"]
    lines += ["", "## 3. Value outside ICP band", ""]
    lines += out_of_band or ["_None._"]
    lines += ["", "## 4. Suppressed or excluded", ""]
    lines += suppressed or ["_None._"]
    lines += [""]
    lines.append(
        "Note: ai-sales-os never auto-sends outreach. "
        "Review each exception before acting."
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_qualified(path: Path, evaluated: list[dict], provenance: dict) -> None:
    """Full per-row evidence with provenance. Deterministic JSON."""
    records = []
    for ev in evaluated:
        records.append({
            "id": (ev["row"].get("id") or "").strip() or f"row-{ev['row_number']}",
            "qualified": ev["qualified"],
            "score": ev["score"],
            "rules": ev["rules"],
            "suppressed": ev["suppressed"],
            "value_parsed": ev["value_parsed"],
            "days_since_last_touch": ev["days_since_last_touch"],
            "domain": ev["domain"],
            "fields": ev["row"],
            "provenance": {
                "source_file": provenance["source_file"],
                "row_number": ev["row_number"],
                "icp_file": provenance["icp_file"],
            },
        })
    with path.open("w", encoding="utf-8") as fh:
        json.dump(records, fh, indent=2, sort_keys=True)
        fh.write("\n")


def write_run_meta(path: Path, *, run_id: str, run_date: str, opps_file: str,
                   icp_file: str, opps_sha256: str, icp_sha256: str,
                   row_count: int, qualified_count: int) -> None:
    meta = {
        "run_id": run_id,
        "run_date": run_date,
        "run_timestamp": datetime.now(timezone.utc).isoformat(),
        "opportunities_file": opps_file,
        "opportunities_sha256": opps_sha256,
        "icp_file": icp_file,
        "icp_sha256": icp_sha256,
        "rows_evaluated": row_count,
        "rows_qualified": qualified_count,
        "tool": "ai-sales-os",
        "version": __import__("ai_sales_os").__version__,
    }
    with path.open("w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2, sort_keys=True)
        fh.write("\n")
